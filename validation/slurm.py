"""SLURM job arrays for the campaign's jobs.

Jobs are grouped by thread count, and each group is cut into chunks of at most
max_array_size jobs (SLURM's MaxArraySize, 1001 by default, caps array indices). Each chunk
becomes an array script `array_t<threads>[_<k>].sbatch` whose task i runs job line i. The
job lines are embedded in the script itself, because sbatch keeps a copy of the script at
submission: a later `slurm` call rewriting the files cannot shift the lines under tasks that
are still queued. `jobs_t<threads>[_<k>].txt` is a readable copy of each chunk's lines.
Every line first checks the job's `.done` marker, so a task whose job is already done does
nothing. Cluster specifics (partition, account, time and memory limits, module loads) come
from the user-edited validation/slurm.conf, never from the code.
"""

from __future__ import annotations

import shlex
from collections.abc import Sequence
from pathlib import Path

from .core import Job

REPO = Path(__file__).resolve().parents[1]
DEFAULT_CONF = REPO / "validation" / "slurm.conf"
EXAMPLE_CONF = REPO / "validation" / "slurm.conf.example"
KEYS = ("partition", "account", "time", "mem", "max_concurrent", "setup")
DEFAULT_MAX_ARRAY_SIZE = 1000   # SLURM's default MaxArraySize is 1001: indices up to 1000
_END = "ODSP_JOBS_END"          # heredoc delimiter of the embedded job list


def read_conf(path: Path) -> dict[str, str]:
    """Read `key = value` lines ('#' starts a comment line, blank lines ignored). Every key of
    KEYS must be present (partition, account, mem, max_concurrent and setup may be empty);
    a missing file or key is an error pointing to validation/slurm.conf.example. The optional
    max_array_size (default 1000) must be a positive integer."""
    path = Path(path)
    hint = f"copy {EXAMPLE_CONF.relative_to(REPO)} to {path} and edit it for your cluster"
    if not path.exists():
        raise FileNotFoundError(f"no SLURM configuration {path}: {hint}")
    conf: dict[str, str] = {}
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        key, eq, value = line.partition("=")
        if not eq or not key.strip():
            raise ValueError(f"{path}:{n}: expected 'key = value', got '{line}' ({hint})")
        conf[key.strip()] = value.strip()
    missing = [k for k in KEYS if k not in conf]
    if missing:
        raise ValueError(f"{path}: missing key(s) {', '.join(missing)} "
                         f"(see {EXAMPLE_CONF.relative_to(REPO)})")
    if not conf["time"]:
        raise ValueError(f"{path}: 'time' must be set (a SLURM time limit such as 04:00:00)")
    if conf["max_concurrent"] and not (conf["max_concurrent"].isdigit()
                                       and int(conf["max_concurrent"]) > 0):
        raise ValueError(f"{path}: max_concurrent must be a positive integer or empty "
                         f"(got '{conf['max_concurrent']}')")
    size = conf.get("max_array_size", "")
    if size and not (size.isdigit() and int(size) > 0):
        raise ValueError(f"{path}: max_array_size must be a positive integer (got '{size}')")
    return conf


def job_line(job: Job) -> str:
    """The shell line of one job: nothing when it is already done, otherwise run it from the
    repository and mark it done on success."""
    args = " ".join(shlex.quote(a) for a in job.args)
    done = shlex.quote(f"{job.prefix}.done")
    line = (f"[ -e {done} ] || {{ cd {shlex.quote(str(REPO))} && bin/odsp {args} && "
            f"touch {done}; }}")
    if "\n" in line:
        raise ValueError(f"{job.prefix}: a job's arguments must not contain line breaks")
    return line


def _script(threads: int, lines: list[str], conf: dict[str, str], logs: Path, name: str) -> str:
    limit = f"%{conf['max_concurrent']}" if conf.get("max_concurrent") else ""
    head = [
        "#!/bin/bash",
        f"#SBATCH --job-name=odsp-t{threads}",
        f"#SBATCH --array=1-{len(lines)}{limit}",
        "#SBATCH --ntasks=1",
        f"#SBATCH --cpus-per-task={threads}",
    ]
    for key in ("partition", "account", "time", "mem"):
        if conf.get(key):
            head.append(f"#SBATCH --{key}={conf[key]}")
    head.append(f"#SBATCH --output={logs}/{name}_%A_%a.out")
    body = [
        "",
        "# Generated by python -m validation.campaign slurm. Task i runs job line i of the list",
        "# embedded below (sbatch keeps this copy, so later `slurm` calls cannot change it).",
        "set -eo pipefail",
        'case "${SLURM_ARRAY_TASK_ID:-}" in',
        f"    ''|*[!0-9]*|0) echo \"not a task of this array (1..{len(lines)}): "
        "'${SLURM_ARRAY_TASK_ID:-}'\" >&2; exit 2 ;;",
        "esac",
    ]
    if conf.get("setup"):
        body.append(conf["setup"])
    body += [f"line=$(sed -n \"${{SLURM_ARRAY_TASK_ID}}p\" <<'{_END}'", *lines, _END, ")"]
    body += [
        'if [ -z "$line" ]; then',
        f'    echo "no job line for task $SLURM_ARRAY_TASK_ID (this array has {len(lines)})" >&2',
        "    exit 2",
        "fi",
        'echo "$line"',
        'eval "$line"',
    ]
    return "\n".join(head + body) + "\n"


def write_arrays(jobs: Sequence[Job], conf: dict[str, str], out_dir: Path) -> list[Path]:
    """Write array scripts (and readable job lists) into `out_dir` for `jobs`, replacing the
    scripts and lists of an earlier call (already submitted scripts are unaffected: they carry
    their own lines), and return the scripts. Each thread count gets array_t<n>.sbatch and
    jobs_t<n>.txt, or, with more jobs than max_array_size (default 1000), array_t<n>_<k>.sbatch
    and jobs_t<n>_<k>.txt for k = 1, 2, ... Each script requests --cpus-per-task=<n> and the
    conf's partition, account, time and memory (an empty value leaves that line out), runs the
    conf's setup line and then job line ${SLURM_ARRAY_TASK_ID} (a missing or out-of-range task
    id exits 2); at most max_concurrent tasks run at once. Each job's output folder is created
    here, so the tasks need not."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in (*out_dir.glob("jobs_t*.txt"), *out_dir.glob("array_t*.sbatch")):
        old.unlink()
    logs = out_dir / "logs"
    logs.mkdir(exist_ok=True)
    size = int(conf.get("max_array_size") or DEFAULT_MAX_ARRAY_SIZE)
    groups: dict[int, list[Job]] = {}
    for j in jobs:
        groups.setdefault(j.threads, []).append(j)
    scripts: list[Path] = []
    for threads, group in sorted(groups.items()):
        for j in group:
            j.prefix.parent.mkdir(parents=True, exist_ok=True)
        chunks = [group[i:i + size] for i in range(0, len(group), size)]
        for k, chunk in enumerate(chunks, 1):
            tag = f"t{threads}" if len(chunks) == 1 else f"t{threads}_{k}"
            lines = [job_line(j) for j in chunk]
            (out_dir / f"jobs_{tag}.txt").write_text("".join(l + "\n" for l in lines),
                                                      encoding="utf-8")
            script = out_dir / f"array_{tag}.sbatch"
            script.write_text(_script(threads, lines, conf, logs, tag), encoding="utf-8")
            scripts.append(script)
    return scripts
